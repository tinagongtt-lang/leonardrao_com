# en_GB and en_AU reuse en_US translations
TRANSLATIONS['en_GB'] = TRANSLATIONS['en_US']
TRANSLATIONS['en_AU'] = TRANSLATIONS['en_US']

for locale, mapping in TRANSLATIONS.items():
    po_path = BASE / locale / 'LC_MESSAGES' / 'django.po'
    po = polib.pofile(str(po_path))
    for entry in po:
        if entry.msgid in mapping:
            entry.msgstr = mapping[entry.msgid]
    po.save()
    print(f'Filled {locale}')
